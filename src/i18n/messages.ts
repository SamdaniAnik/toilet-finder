/** Number helpers for a locale ("bn-BD" gives Bengali digits). */
function numbers(locale: string) {
  const int = new Intl.NumberFormat(locale, { maximumFractionDigits: 0 });
  const one = new Intl.NumberFormat(locale, { minimumFractionDigits: 1, maximumFractionDigits: 1 });
  const money = new Intl.NumberFormat(locale, { maximumFractionDigits: 2 });
  return { int: (n: number) => int.format(n), one: (n: number) => one.format(n), money: (n: number) => money.format(n) };
}

